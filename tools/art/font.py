def build(out_dir, name='pixel'):
    os.makedirs(out_dir, exist_ok=True)
    CELL_H = 10
    chars = [' '] + sorted(G.keys(), key=lambda c: ord(c))
    # fix 'a' (its definition above is messy) -> define cleanly
    G['a'] = [".....", ".....", ".###.", "....#", ".####", "#...#", ".####"]
    widths = {}
    for ch in chars:
        if ch == ' ':
            widths[ch] = 2
        else:
            widths[ch] = max(len(r) for r in G[ch])
    atlas_w = 256
    x = y = 0
    pos = {}
    for ch in chars:
        w = widths[ch]
        if x + w + 1 > atlas_w:
            x = 0; y += CELL_H + 1
        pos[ch] = (x, y)
        x += w + 1
    atlas_h = y + CELL_H + 1
    atlas_h = 1 << (atlas_h - 1).bit_length()
    img = Image.new('RGBA', (atlas_w, atlas_h), (0, 0, 0, 0))
    px = img.load()
    for ch in chars:
        if ch == ' ':
            continue
        ox, oy = pos[ch]
        for j, row in enumerate(G[ch]):
            for i, c in enumerate(row):
                if c == '#':
                    px[ox + i, oy + 1 + j] = (255, 255, 255, 255)
    img.save(os.path.join(out_dir, name + '.png'))
    lines = [
        f'info face="LIMPixel" size={CELL_H} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=0 padding=0,0,0,0 spacing=1,1 outline=0',
        f'common lineHeight={CELL_H + 2} base=8 scaleW={atlas_w} scaleH={atlas_h} pages=1 packed=0 alphaChnl=0 redChnl=4 greenChnl=4 blueChnl=4',
        f'page id=0 file="{name}.png"',
        f'chars count={len(chars)}',
    ]
    for ch in chars:
        ox, oy = pos[ch]
        w = widths[ch]
        adv = w + 1 if ch != ' ' else 3
        lines.append(f'char id={ord(ch)} x={ox} y={oy} width={w} height={CELL_H} xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15')
    with open(os.path.join(out_dir, name + '.fnt'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    return img


if __name__ == '__main__':
    im = build('_preview/font')
